export const GLYPH_W = 5;
export const GLYPH_H = 7;

const cache = new Map();

/** 文本像素宽度（含字间距）。 */
export function textWidth(text, scale = 2, tracking = 1) {
  if (!text) return 0;
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

/**
 * 渲染一行像素文字到 canvas。
 * @param {string} text 仅支持字模表中的字符（自动转大写）
 */
export function renderText(text, opts = {}) {
  const {
    scale = 2,
    color = "#ffe08a",
    outline = null,
    shadow = null,
    tracking = 1,
    align = "left",
  } = opts;

  const s = String(text).toUpperCase();
  const cw = GLYPH_W * scale;
  const ch = GLYPH_H * scale;
  const gap = tracking * scale;
  const w = Math.max(1, textWidth(s, scale, tracking));
  const pad = (outline ? scale : 0) + (shadow ? scale * 2 : 0);
  const canvasW = w + pad * 2;
  const canvasH = ch + pad * 2;

  const key = `${s}|${scale}|${color}|${outline}|${shadow}|${tracking}`;
  // 缓存里放的是「母版」，每次返回一张拷贝：
  // canvas.cloneNode 不会复制像素（克隆出来是空白的），所以必须 drawImage 复制。
  const copy = (src) => {
    const c = document.createElement("canvas");
    c.width = src.width;
    c.height = src.height;
    c.getContext("2d").drawImage(src, 0, 0);
    return c;
  };
  const cached = cache.get(key);
  if (cached) return copy(cached);

  const canvas = document.createElement("canvas");
  canvas.width = canvasW;
  canvas.height = canvasH;
  const ctx = canvas.getContext("2d");
  ctx.imageSmoothingEnabled = false;

  const put = (ox, oy, col) => {
    ctx.fillStyle = col;
    for (let i = 0; i < s.length; i++) {
      const g = G[s[i]] || G["?"];
      const gx = pad + i * (cw + gap) + ox;
      for (let ry = 0; ry < GLYPH_H; ry++) {
        const row = g[ry];
        for (let rx = 0; rx < GLYPH_W; rx++) {
          if (row[rx] === "1") ctx.fillRect(gx + rx * scale, pad + ry * scale + oy, scale, scale);
        }
      }
    }
  };

  if (shadow) put(scale, scale * 2, shadow);
  if (outline) {
    for (const [dx, dy] of [[-scale, 0], [scale, 0], [0, -scale], [0, scale]]) put(dx, dy, outline);
  }
  put(0, 0, color);

  cache.set(key, canvas);
  return copy(canvas);
}

/**
 * 把元素内容替换为像素字体 canvas，返回可更新的句柄。
 * 用于动态数值（FPS / 坐标 / 时钟）。
 */
export function attachPixelText(el, opts = {}) {
  if (!el) return { set() {} };
  const holder = document.createElement("span");
  holder.style.display = "inline-block";
  holder.style.lineHeight = "0";
  el.textContent = "";
  el.appendChild(holder);

  let last = null;
  const api = {
    set(text) {
      if (text === last) return;
      last = text;
      const canvas = renderText(text, opts);
      canvas.style.imageRendering = "pixelated";
      canvas.style.display = "block";
      holder.textContent = "";
      holder.appendChild(canvas);
    },
    el: holder,
  };
  api.set(opts.initial || "");
  return api;
}

/** 静态像素文本：一次性替换元素内容。 */
export function setPixelText(el, text, opts = {}) {
  if (!el) return null;
  const canvas = renderText(text, opts);
  canvas.style.imageRendering = "pixelated";
  canvas.style.display = "block";
  canvas.style.margin = opts.center ? "0 auto" : "0";
  el.textContent = "";
  el.appendChild(canvas);
  return canvas;
}
